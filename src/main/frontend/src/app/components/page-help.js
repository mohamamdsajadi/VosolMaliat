'use client';
import { useId, useRef } from 'react';
import styles from './page-help.module.css';

export default function PageHelp({ title = 'راهنمای صفحه', children }) {
  const dialog = useRef(null);
  const id = useId();
  return <><button type="button" className={styles.button} aria-label={title} aria-haspopup="dialog" onClick={() => dialog.current.showModal()}>
    <svg width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.8" aria-hidden="true"><circle cx="12" cy="12" r="9" /><path d="M12 11v6M12 7v1" /></svg>
  </button><dialog ref={dialog} className={styles.dialog} aria-labelledby={id} onClick={event => { if (event.target === event.currentTarget) dialog.current.close(); }}>
    <header><h2 id={id}>{title}</h2><button type="button" aria-label="بستن راهنما" onClick={() => dialog.current.close()}>×</button></header>
    <div className={styles.content}>{children}</div>
  </dialog></>;
}

